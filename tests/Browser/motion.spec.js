import { test, expect } from '@playwright/test'

const contour = (page) => page.locator('.coast-outline')

test('organic contour morphs, responds to pointer and freezes offscreen', async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.goto('/')
    const card = page.locator('.package-card').first()
    await expect(card).not.toHaveClass(/revealed/)
    const before = await contour(page).getAttribute('d')
    await expect.poll(() => contour(page).getAttribute('d')).not.toBe(before)
    const scene = page.locator('.coastline-scene')
    const bounds = await scene.boundingBox()
    const photo = page.locator('.coastline-scene image')
    const initial = await photo.getAttribute('transform')
    await page.mouse.move(bounds.x + bounds.width * 0.8, bounds.y + bounds.height * 0.3)
    await expect.poll(() => photo.getAttribute('transform')).not.toBe(initial)
    await expect(page.locator('.coast-traveller')).toHaveAttribute('transform', /translate/)
    await page.locator('.site-footer').scrollIntoViewIfNeeded()
    await expect(page.locator('.hero-visual')).toHaveClass(/motion-paused/)
    const frozen = await contour(page).getAttribute('d')
    await page.waitForTimeout(150)
    await expect(contour(page)).toHaveAttribute('d', frozen)
    await card.scrollIntoViewIfNeeded()
    await expect(card).toHaveClass(/revealed/)
    await expect(card).toHaveCSS('opacity', '1')
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/')
    await expect
        .poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
        .toBe(true)
    await expect(page.locator('.hero-visual').getByRole('button')).toHaveCount(0)
    await expect(page.locator('.site-footer').getByRole('button')).toHaveCount(0)
    await expect(
        page.locator('.site-footer').getByRole('link', { name: 'Area admin' }),
    ).toHaveCount(0)
})

test('reduced motion freezes the contour and changes live without reloading', async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/')
    const frozen = await contour(page).getAttribute('d')
    await page.waitForTimeout(150)
    await expect(contour(page)).toHaveAttribute('d', frozen)
    await expect(page.locator('.package-card').first()).toHaveCSS('opacity', '1')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await expect.poll(() => contour(page).getAttribute('d')).not.toBe(frozen)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await expect(contour(page)).toHaveAttribute('d', frozen)
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.goto('/')
    const card = page.locator('.package-card').first()
    await card.getByRole('link').focus()
    await expect(card).toHaveClass(/revealed/)
    await expect(card).toHaveCSS('opacity', '1')
})
