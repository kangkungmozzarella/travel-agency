import { test, expect } from '@playwright/test'

const island = (page) => page.locator('.island-scene')
const clock = (page) => island(page).getAttribute('data-time')

test('3D island animates, responds to pointer and freezes offscreen', async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.goto('/')
    const card = page.locator('.package-card').first()
    await expect(card).not.toHaveClass(/revealed/)
    await expect(island(page)).toHaveClass(/island-ready/)
    await expect(island(page).locator('.island-pin')).toHaveCount(4)
    const before = await clock(page)
    await expect.poll(() => clock(page)).not.toBe(before)
    const bounds = await island(page).boundingBox()
    await page.mouse.move(bounds.x + bounds.width * 0.9, bounds.y + bounds.height * 0.3)
    await expect
        .poll(async () => Number(await island(page).getAttribute('data-pointer')))
        .toBeGreaterThan(0.2)
    await page.locator('.site-footer').scrollIntoViewIfNeeded()
    await expect(page.locator('.hero-visual')).toHaveClass(/motion-paused/)
    const frozen = await clock(page)
    await page.waitForTimeout(150)
    await expect(island(page)).toHaveAttribute('data-time', frozen)
    await card.scrollIntoViewIfNeeded()
    await expect(card).toHaveCSS('opacity', '1')
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/')
    await expect
        .poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
        .toBe(true)
    await expect(page.locator('.hero-visual').getByRole('button')).toHaveCount(0)
    await expect(page.locator('.site-footer').getByRole('button')).toHaveCount(0)
    await expect(
        page.locator('.site-footer').getByRole('link', { name: 'Area admin' }),
    ).toHaveCount(0)
})

test('reduced motion freezes the island and changes live without reloading', async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/')
    await expect(island(page)).toHaveClass(/island-ready/)
    await expect(island(page)).toHaveAttribute('data-time', '0')
    await page.waitForTimeout(150)
    await expect(island(page)).toHaveAttribute('data-time', '0')
    await expect(page.locator('.package-card').first()).toHaveCSS('opacity', '1')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await expect.poll(() => clock(page)).not.toBe('0')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await expect(island(page)).toHaveAttribute('data-time', '0')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.goto('/travel-packages')
    const card = page.locator('.package-card').first()
    await card.getByRole('link').focus()
    await expect(card).toHaveClass(/revealed/)
    await expect(card).toHaveCSS('opacity', '1')
})
